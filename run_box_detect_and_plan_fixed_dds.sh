#!/usr/bin/env bash
set -euo pipefail

cd "${ARMS_DIR:-$HOME/ARMS}"

DDS_WRAPPER="${DDS_WRAPPER:-/home/unitree/cyclonedds_py_0_10_fix/run_with_fixed_dds.sh}"
PYTHON_BIN="${PYTHON_BIN:-python3}"
NETWORK_INTERFACE="${NETWORK_INTERFACE:-eth0}"

DETECTOR="${DETECTOR:-server}"
SERVER_URL="${SERVER_URL:-http://192.168.10.179:8000}"
BOX_MODEL="${BOX_MODEL:-}"
BOX_CLASS="${BOX_CLASS:-box}"
CAMERA_MODE="${CAMERA_MODE:-realsense}"
COLOR_FPS="${COLOR_FPS:-30}"
DEPTH_WIDTH="${DEPTH_WIDTH:-640}"
DEPTH_HEIGHT="${DEPTH_HEIGHT:-480}"
DEPTH_FPS="${DEPTH_FPS:-30}"
BOX_DISTANCE="${BOX_DISTANCE:-0.60}"
DEPTH_ROI_RATIO="${DEPTH_ROI_RATIO:-0.45}"
DEPTH_STAT="${DEPTH_STAT:-nearest_percentile}"
DEPTH_PERCENTILE="${DEPTH_PERCENTILE:-20}"
MIN_DEPTH="${MIN_DEPTH:-0.15}"
MAX_DEPTH="${MAX_DEPTH:-0.85}"
BBOX_EDGE_MARGIN_PX="${BBOX_EDGE_MARGIN_PX:-2.0}"
MAX_OBJECT_LAST_SEEN_S="${MAX_OBJECT_LAST_SEEN_S:-0.75}"
DEPTH_FALLBACK="${DEPTH_FALLBACK:-none}"
BOX_WIDTH="${BOX_WIDTH:-0.28}"
BOX_HEIGHT="${BOX_HEIGHT:-0.16}"
BOX_DEPTH="${BOX_DEPTH:-0.20}"
SIDE_CLEARANCE="${SIDE_CLEARANCE:-0.065}"
GRASP_STRATEGY="${GRASP_STRATEGY:-flat-squeeze}"
SQUEEZE_SIDE_CLEARANCE="${SQUEEZE_SIDE_CLEARANCE:--0.015}"
SQUEEZE_DURATION="${SQUEEZE_DURATION:-2.0}"
MAX_TWO_HAND_CENTER_Y="${MAX_TWO_HAND_CENTER_Y:-0.10}"
GRASP_CENTER_Y_MODE="${GRASP_CENTER_Y_MODE:-zero}"
GRASP_CENTER_Y_LIMIT="${GRASP_CENTER_Y_LIMIT:-0.08}"
CAMERA_INDEX="${CAMERA_INDEX:-0}"
CAMERA_PITCH_DOWN_DEG="${CAMERA_PITCH_DOWN_DEG:-42}"
MIN_CONFIDENCE="${MIN_CONFIDENCE:-0.25}"
DETECT_MAX_TIME="${DETECT_MAX_TIME:-8}"
CONTEXT_FRAME_MATCH="${CONTEXT_FRAME_MATCH:-exact}"
PALM_FORWARD_OFFSET="${PALM_FORWARD_OFFSET:-0.00}"
PALM_UP_OFFSET="${PALM_UP_OFFSET:-0.075}"
MAX_PALM_TARGET_X="${MAX_PALM_TARGET_X:-0.48}"
MIN_PALM_TARGET_Z="${MIN_PALM_TARGET_Z:-0.08}"
MAX_PALM_TARGET_Z="${MAX_PALM_TARGET_Z:-0.22}"
HAND_SEQUENCE="${HAND_SEQUENCE:-open-only}"
GRASP_METHOD="${GRASP_METHOD:-flat_palm}"
PREGRASP_DURATION="${PREGRASP_DURATION:-4.0}"
MAX_ERROR="${MAX_ERROR:-0.045}"

OBSTACLE_CHECK="${OBSTACLE_CHECK:-realsense}"
OBSTACLE_JSON="${OBSTACLE_JSON:-}"
OBSTACLE_SAVE_JSON="${OBSTACLE_SAVE_JSON:-runs/box_obstacle_cloud_latest.json}"
OBSTACLE_CLEARANCE="${OBSTACLE_CLEARANCE:-0.07}"
OBSTACLE_EXTRA_CLEARANCE="${OBSTACLE_EXTRA_CLEARANCE:-0.03}"
OBSTACLE_SAMPLES_PER_LEG="${OBSTACLE_SAMPLES_PER_LEG:-36}"
OBSTACLE_CAPTURE_S="${OBSTACLE_CAPTURE_S:-0.3}"
OBSTACLE_STRIDE_PX="${OBSTACLE_STRIDE_PX:-10}"
OBSTACLE_MIN_DEPTH="${OBSTACLE_MIN_DEPTH:-0.15}"
OBSTACLE_MAX_DEPTH="${OBSTACLE_MAX_DEPTH:-1.50}"
OBSTACLE_VOXEL_SIZE="${OBSTACLE_VOXEL_SIZE:-0.025}"
OBSTACLE_MAX_POINTS="${OBSTACLE_MAX_POINTS:-2500}"
OBSTACLE_EXCLUDE_TARGET_RADIUS="${OBSTACLE_EXCLUDE_TARGET_RADIUS:-0.18}"
OBSTACLE_EARLY_ACCEPT_DISTANCE="${OBSTACLE_EARLY_ACCEPT_DISTANCE:-0.10}"
MIN_OPEN_VIA_UP="${MIN_OPEN_VIA_UP:-0.10}"
MIN_OPEN_VIA_SIDE_EXTRA="${MIN_OPEN_VIA_SIDE_EXTRA:-0.12}"
HAND_ENVELOPE_LENGTH="${HAND_ENVELOPE_LENGTH:-0.10}"
HAND_ENVELOPE_WIDTH="${HAND_ENVELOPE_WIDTH:-0.09}"
HAND_ENVELOPE_CLEARANCE="${HAND_ENVELOPE_CLEARANCE:-0.03}"
AVOIDANCE_MODE="${AVOIDANCE_MODE:-basic}"
AVOIDANCE_UP_VALUES="${AVOIDANCE_UP_VALUES:-0.10,0.18,0.28}"
AVOIDANCE_SIDE_EXTRA_VALUES="${AVOIDANCE_SIDE_EXTRA_VALUES:-0.00,0.06,0.12}"
AVOIDANCE_FORWARD_VALUES="${AVOIDANCE_FORWARD_VALUES:--0.16,-0.08,0.0}"
AVOIDANCE_MAX_ERROR="${AVOIDANCE_MAX_ERROR:-0.045}"
AVOIDANCE_ITERATIONS="${AVOIDANCE_ITERATIONS:-60}"
AVOIDANCE_MAX_CANDIDATES="${AVOIDANCE_MAX_CANDIDATES:-24}"
AVOIDANCE_REPLANS="${AVOIDANCE_REPLANS:-2}"
AVOIDANCE_REPLAN_SCALE="${AVOIDANCE_REPLAN_SCALE:-1.5}"

EXECUTE="${EXECUTE:-0}"
LOG_FILE="${LOG_FILE:-box_detect_and_plan.log}"
SNAPSHOT_FILE="${SNAPSHOT_FILE:-before_box_two_hand.json}"
PATH_FILE="${PATH_FILE:-runs/box_two_hand_last_path.json}"
STOP_CAMERA_PREVIEW="${STOP_CAMERA_PREVIEW:-1}"

if [[ "$CAMERA_MODE" == "realsense" && "$STOP_CAMERA_PREVIEW" == "1" ]]; then
  preview_pids="$(pgrep -f '[c]amera_h265_sender' || true)"
  if [[ -n "$preview_pids" ]]; then
    echo "STOP_CAMERA_PREVIEW=1 stopping camera_h265_sender pids=$preview_pids"
    for pid in $preview_pids; do
      parent_pid="$(ps -o ppid= -p "$pid" | tr -d ' ' || true)"
      kill "$pid" 2>/dev/null || true
      if [[ -n "$parent_pid" && "$parent_pid" != "1" ]]; then
        kill "$parent_pid" 2>/dev/null || true
      fi
    done
    sleep 2
  fi
fi

args=(
  -B -m arms.task8_detect_box_and_plan
  --detector "$DETECTOR"
  --server-url "$SERVER_URL"
  --target-class "$BOX_CLASS"
  --camera-index "$CAMERA_INDEX"
  --camera-mode "$CAMERA_MODE"
  --color-fps "$COLOR_FPS"
  --depth-width "$DEPTH_WIDTH"
  --depth-height "$DEPTH_HEIGHT"
  --depth-fps "$DEPTH_FPS"
  --box-distance "$BOX_DISTANCE"
  --depth-roi-ratio "$DEPTH_ROI_RATIO"
  --depth-stat "$DEPTH_STAT"
  --depth-percentile "$DEPTH_PERCENTILE"
  --min-depth "$MIN_DEPTH"
  --max-depth "$MAX_DEPTH"
  --bbox-edge-margin-px "$BBOX_EDGE_MARGIN_PX"
  --max-object-last-seen-s "$MAX_OBJECT_LAST_SEEN_S"
  --depth-fallback "$DEPTH_FALLBACK"
  --detect-max-time "$DETECT_MAX_TIME"
  --min-confidence "$MIN_CONFIDENCE"
  --context-frame-match "$CONTEXT_FRAME_MATCH"
  --camera-pitch-down-deg "$CAMERA_PITCH_DOWN_DEG"
  --box-width "$BOX_WIDTH"
  --box-height "$BOX_HEIGHT"
  --box-depth "$BOX_DEPTH"
  --side-clearance "$SIDE_CLEARANCE"
  --grasp-strategy "$GRASP_STRATEGY"
  --squeeze-side-clearance "$SQUEEZE_SIDE_CLEARANCE"
  --squeeze-duration "$SQUEEZE_DURATION"
  --max-two-hand-center-y "$MAX_TWO_HAND_CENTER_Y"
  --grasp-center-y-mode "$GRASP_CENTER_Y_MODE"
  --grasp-center-y-limit "$GRASP_CENTER_Y_LIMIT"
  --palm-forward-offset "$PALM_FORWARD_OFFSET"
  --palm-up-offset "$PALM_UP_OFFSET"
  --max-palm-target-x "$MAX_PALM_TARGET_X"
  --min-palm-target-z "$MIN_PALM_TARGET_Z"
  --max-palm-target-z "$MAX_PALM_TARGET_Z"
  --hand-sequence "$HAND_SEQUENCE"
  --grasp-method "$GRASP_METHOD"
  --network-interface "$NETWORK_INTERFACE"
  --pregrasp-duration "$PREGRASP_DURATION"
  --max-error "$MAX_ERROR"
  --obstacle-check "$OBSTACLE_CHECK"
  --obstacle-save-json "$OBSTACLE_SAVE_JSON"
  --obstacle-clearance "$OBSTACLE_CLEARANCE"
  --obstacle-extra-clearance "$OBSTACLE_EXTRA_CLEARANCE"
  --obstacle-samples-per-leg "$OBSTACLE_SAMPLES_PER_LEG"
  --obstacle-capture-s "$OBSTACLE_CAPTURE_S"
  --obstacle-stride-px "$OBSTACLE_STRIDE_PX"
  --obstacle-min-depth "$OBSTACLE_MIN_DEPTH"
  --obstacle-max-depth "$OBSTACLE_MAX_DEPTH"
  --obstacle-voxel-size "$OBSTACLE_VOXEL_SIZE"
  --obstacle-max-points "$OBSTACLE_MAX_POINTS"
  --obstacle-exclude-target-radius "$OBSTACLE_EXCLUDE_TARGET_RADIUS"
  --obstacle-early-accept-distance "$OBSTACLE_EARLY_ACCEPT_DISTANCE"
  --min-open-via-up "$MIN_OPEN_VIA_UP"
  --min-open-via-side-extra "$MIN_OPEN_VIA_SIDE_EXTRA"
  --hand-envelope-length "$HAND_ENVELOPE_LENGTH"
  --hand-envelope-width "$HAND_ENVELOPE_WIDTH"
  --hand-envelope-clearance "$HAND_ENVELOPE_CLEARANCE"
  --avoidance-mode "$AVOIDANCE_MODE"
  --avoidance-up-values="$AVOIDANCE_UP_VALUES"
  --avoidance-side-extra-values="$AVOIDANCE_SIDE_EXTRA_VALUES"
  --avoidance-forward-values="$AVOIDANCE_FORWARD_VALUES"
  --avoidance-max-error "$AVOIDANCE_MAX_ERROR"
  --avoidance-iterations "$AVOIDANCE_ITERATIONS"
  --avoidance-max-candidates "$AVOIDANCE_MAX_CANDIDATES"
  --avoidance-replans "$AVOIDANCE_REPLANS"
  --avoidance-replan-scale "$AVOIDANCE_REPLAN_SCALE"
  --snapshot-file "$SNAPSHOT_FILE"
  --path-file "$PATH_FILE"
  --log-file "$LOG_FILE"
)

if [[ -n "$BOX_MODEL" ]]; then
  args+=(--model "$BOX_MODEL")
fi

if [[ "$OBSTACLE_CHECK" == "json" ]]; then
  args+=(--obstacle-json "$OBSTACLE_JSON")
fi

if [[ "$EXECUTE" == "1" ]]; then
  args+=(--execute)
fi

echo "ARMS_DIR=$(pwd)"
echo "DETECTOR=$DETECTOR"
echo "SERVER_URL=$SERVER_URL"
echo "BOX_MODEL=$BOX_MODEL"
echo "BOX_CLASS=$BOX_CLASS"
echo "CAMERA_MODE=$CAMERA_MODE"
echo "BOX_DISTANCE=$BOX_DISTANCE"
echo "DEPTH_ROI_RATIO=$DEPTH_ROI_RATIO"
echo "DEPTH_STAT=$DEPTH_STAT"
echo "DEPTH_PERCENTILE=$DEPTH_PERCENTILE"
echo "MIN_DEPTH=$MIN_DEPTH"
echo "MAX_DEPTH=$MAX_DEPTH"
echo "BBOX_EDGE_MARGIN_PX=$BBOX_EDGE_MARGIN_PX"
echo "MAX_OBJECT_LAST_SEEN_S=$MAX_OBJECT_LAST_SEEN_S"
echo "DEPTH_FALLBACK=$DEPTH_FALLBACK"
echo "CONTEXT_FRAME_MATCH=$CONTEXT_FRAME_MATCH"
echo "MAX_TWO_HAND_CENTER_Y=$MAX_TWO_HAND_CENTER_Y"
echo "GRASP_CENTER_Y_MODE=$GRASP_CENTER_Y_MODE"
echo "GRASP_CENTER_Y_LIMIT=$GRASP_CENTER_Y_LIMIT"
echo "PALM_UP_OFFSET=$PALM_UP_OFFSET"
echo "MAX_PALM_TARGET_X=$MAX_PALM_TARGET_X"
echo "MIN_PALM_TARGET_Z=$MIN_PALM_TARGET_Z"
echo "MAX_PALM_TARGET_Z=$MAX_PALM_TARGET_Z"
echo "HAND_SEQUENCE=$HAND_SEQUENCE"
echo "GRASP_METHOD=$GRASP_METHOD"
echo "GRASP_STRATEGY=$GRASP_STRATEGY"
echo "SQUEEZE_SIDE_CLEARANCE=$SQUEEZE_SIDE_CLEARANCE"
echo "SQUEEZE_DURATION=$SQUEEZE_DURATION"
echo "MAX_ERROR=$MAX_ERROR"
echo "OBSTACLE_CHECK=$OBSTACLE_CHECK"
echo "OBSTACLE_CLEARANCE=$OBSTACLE_CLEARANCE"
echo "OBSTACLE_EXTRA_CLEARANCE=$OBSTACLE_EXTRA_CLEARANCE"
echo "MIN_OPEN_VIA_UP=$MIN_OPEN_VIA_UP"
echo "MIN_OPEN_VIA_SIDE_EXTRA=$MIN_OPEN_VIA_SIDE_EXTRA"
echo "HAND_ENVELOPE_LENGTH=$HAND_ENVELOPE_LENGTH"
echo "HAND_ENVELOPE_WIDTH=$HAND_ENVELOPE_WIDTH"
echo "HAND_ENVELOPE_CLEARANCE=$HAND_ENVELOPE_CLEARANCE"
echo "AVOIDANCE_MODE=$AVOIDANCE_MODE"
echo "EXECUTE=$EXECUTE"
echo "LOG_FILE=$LOG_FILE"
echo "SNAPSHOT_FILE=$SNAPSHOT_FILE"
echo "PATH_FILE=$PATH_FILE"

if [[ "$EXECUTE" == "1" ]]; then
  exec env -i \
    HOME="$HOME" \
    USER="${USER:-unitree}" \
    LOGNAME="${LOGNAME:-${USER:-unitree}}" \
    PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin" \
    ARMS_DIR="$(pwd)" \
    "$DDS_WRAPPER" "$PYTHON_BIN" "${args[@]}"
fi

exec "$PYTHON_BIN" "${args[@]}"
